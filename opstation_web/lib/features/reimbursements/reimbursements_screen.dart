                style: const TextStyle(fontSize: 12.5, color: AppTheme.textSecondary)),
            const SizedBox(height: 10),
            TextField(controller: reason, autofocus: true, maxLines: 2,
                decoration: const InputDecoration(labelText: 'Reason *', border: OutlineInputBorder())),
          ]),
        ),
        actions: [
          TextButton(onPressed: () => Navigator.pop(d, false), child: const Text('Keep approved')),
          ElevatedButton(onPressed: () => Navigator.pop(d, true), child: const Text('Cancel approval')),
        ],
      ),
    );
    if (ok != true) return;
    if (reason.text.trim().isEmpty) { _snack('Enter the reason'); return; }
    try {
      await _db.rpc('reimb_cancel_approval', params: {'p_claim': c['id'], 'p_reason': reason.text.trim()});
      _snack('Approval cancelled — back to Pending');
      await _load();
    } catch (e) {
      _snack(friendlyError('Could not cancel', e));
    }
  }

  Future<void> _makeAdvice(Map c) async {
    try {
      await _db.rpc('reimb_make_advice', params: {'p_claim': c['id']});
      _snack('Payment Advice created');
      await _load();
    } catch (e) {
      _snack(friendlyError('Could not create the Payment Advice', e));
    }
  }

  // ── actions ───────────────────────────────────────────────────────────────
  /// Approve with the worked-out amount pre-filled; the approver may change it
  /// (e.g. a visit not justified) — a changed amount needs a reason.
  Future<void> _approve(Map c) async {
    final calc = c['status'] == 'pending' || c['status'] == 'rejected' ? _workedOut(c) : null;
    final allowTotal = _allowance(c);
    final amtCtl = TextEditingController(text: calc == null ? '' : '$calc');
    final noteCtl = TextEditingController();
    String? err;
    final ok = await showDialog<bool>(
      context: context,
      builder: (d) => StatefulBuilder(builder: (d, setD) {
        final typed = num.tryParse(amtCtl.text.trim());
        final changed = calc != null && typed != null && typed.round() != calc;
        return AlertDialog(
          title: Text('Approve — ${c['claimant_name'] ?? ''}'),
          content: ConstrainedBox(
            constraints: const BoxConstraints(maxWidth: 420),
            child: Column(mainAxisSize: MainAxisSize.min, crossAxisAlignment: CrossAxisAlignment.start, children: [
              Text(
                [
                  '${_dates(c)} · ${_km(_unpaidKm(c))}'
                      '${_rate == null ? '' : ' × Rs ${NumberFormat('#,##0.##').format(_rate)}/km = ${_rs((_unpaidKm(c) * _rate!).round())}'}',
                  if (allowTotal > 0) 'Allowance ${_rs(allowTotal.round())}',
                  calc == null ? 'No rate per km set — enter the amount' : 'Worked out ${_rs(calc)}',
                ].join('\n'),
                style: const TextStyle(fontSize: 12.5, color: AppTheme.textSecondary),
              ),
              const SizedBox(height: 12),
              TextField(
                controller: amtCtl,
                autofocus: true,
                keyboardType: const TextInputType.numberWithOptions(decimal: true),
                inputFormatters: [FilteringTextInputFormatter.allow(RegExp(r'[0-9.]'))],
                onChanged: (_) => setD(() => err = null),
                decoration: const InputDecoration(labelText: 'Amount to approve (Rs)', isDense: true, border: OutlineInputBorder()),
              ),
              if (changed) ...[
                const SizedBox(height: 10),
                TextField(
                  controller: noteCtl,
                  maxLines: 2,
                  onChanged: (_) => setD(() => err = null),
                  decoration: InputDecoration(
                    labelText: 'Reason for changing the amount *',
                    hintText: 'e.g. 2 visits not justified',
                    helperText: 'Worked out: ${_rs(calc)} · changing by ${_rs((typed!.round() - calc!).abs())}',
                    isDense: true,
                    border: const OutlineInputBorder(),
                  ),
                ),
              ],
              if (err != null) ...[
                const SizedBox(height: 8),
                Text(err!, style: const TextStyle(color: AppTheme.danger, fontSize: 12.5)),
              ],
            ]),
          ),
          actions: [
            TextButton(onPressed: () => Navigator.pop(d, false), child: const Text('Cancel')),
            ElevatedButton(
              style: ElevatedButton.styleFrom(backgroundColor: const Color(0xFF059669), foregroundColor: Colors.white),
              onPressed: () {
                final v = num.tryParse(amtCtl.text.trim());
                if (amtCtl.text.trim().isNotEmpty && (v == null || v < 0)) return setD(() => err = 'Enter a valid amount.');
                if (changed && noteCtl.text.trim().isEmpty) return setD(() => err = 'Enter the reason for changing the amount.');
                Navigator.pop(d, true);
              },
              child: Text(_paMode ? 'Approve & create Payment Advice' : 'Approve'),
            ),
          ],
        );
      }),
    );
    if (ok != true) return;
    final typed = num.tryParse(amtCtl.text.trim());
    try {
      await _db.rpc('reimb_decide', params: {
        'p_claim': c['id'],
        'p_approve': true,
        if (typed != null) 'p_amount': typed,
        if (noteCtl.text.trim().isNotEmpty) 'p_adjust_note': noteCtl.text.trim(),
      });
      _snack(_paMode ? 'Approved — Payment Advice created' : 'Approved — ${c['claimant_name'] ?? ''}');
      await _load();
    } catch (e) {
      _snack(friendlyError('Could not approve', e));
    }
  }

  Future<void> _reject(Map c) async {
    final reason = TextEditingController();
    final ok = await showDialog<bool>(
      context: context,
      builder: (d) => AlertDialog(
        title: Text('Reject — ${c['claimant_name'] ?? ''}'),
        content: SizedBox(
          width: 400,
          child: TextField(controller: reason, autofocus: true, maxLines: 2,
              decoration: const InputDecoration(labelText: 'Reason *', border: OutlineInputBorder())),
        ),
        actions: [
          TextButton(onPressed: () => Navigator.pop(d, false), child: const Text('Cancel')),
          ElevatedButton(onPressed: () => Navigator.pop(d, true), child: const Text('Reject')),
        ],
      ),
    );
    if (ok != true) return;
    if (reason.text.trim().isEmpty) { _snack('Enter the reason'); return; }
    try {
      await _db.rpc('reimb_decide', params: {'p_claim': c['id'], 'p_approve': false, 'p_reason': reason.text.trim()});
      _snack('Rejected');
      await _load();
    } catch (e) {
      _snack(friendlyError('Could not reject', e));
    }
  }

  Future<void> _markPaid(Map c) async {
    // Pre-filled from km × rate per km (editable); the stored amount wins if set at approval.
    final km = _unpaidKm(c);
    final rate = (c['rate'] as num?)?.toDouble() ?? _rate;
    final num? suggested = c['amount'] as num? ?? (rate == null ? null : (km * rate).round());
    final amt = TextEditingController(text: suggested == null ? '' : '${suggested.round()}');
    final ref_ = TextEditingController();
    String method = 'Cash';
    DateTime on = DateTime.now();
    var busy = false;
    await showDialog<void>(
      context: context,
      builder: (ctx) => StatefulBuilder(builder: (ctx, setS) => AlertDialog(
        title: Text('Mark paid — ${c['claimant_name'] ?? ''}'),
        content: SizedBox(
          width: 420,
          child: Column(mainAxisSize: MainAxisSize.min, children: [
            Text('${_dates(c)} · ${_km(km)}'
                '${rate == null ? ' · no rate per km set' : ' × Rs ${NumberFormat('#,##0.##').format(rate)}/km = ${_rs((km * rate).round())}'}',
                style: const TextStyle(fontSize: 12.5, color: AppTheme.textSecondary)),
            const SizedBox(height: 12),
            Row(children: [
              Expanded(child: TextField(
                controller: amt, autofocus: true,
                keyboardType: const TextInputType.numberWithOptions(decimal: true),
                inputFormatters: [FilteringTextInputFormatter.allow(RegExp(r'[0-9.]'))],
                decoration: const InputDecoration(labelText: 'Amount paid (Rs) *', isDense: true, border: OutlineInputBorder()))),
              const SizedBox(width: 10),
              Expanded(child: InkWell(
                onTap: () async {
                  final p = await showDatePicker(context: ctx, initialDate: on, firstDate: DateTime(2020), lastDate: DateTime.now().add(const Duration(days: 30)));
                  if (p != null) setS(() => on = p);
                },
                child: InputDecorator(decoration: const InputDecoration(labelText: 'Paid on', isDense: true, border: OutlineInputBorder()),
                    child: Text(DateFormat('d MMM yyyy').format(on))),
              )),
            ]),
            const SizedBox(height: 10),
            Row(children: [
              Expanded(child: DropdownButtonFormField<String>(
                value: method, isExpanded: true,
                decoration: const InputDecoration(labelText: 'Method', isDense: true, border: OutlineInputBorder()),
                items: [for (final m in const ['Cash', 'Bank transfer', 'Cheque', 'With salary']) DropdownMenuItem(value: m, child: Text(m))],
                onChanged: (v) => setS(() => method = v ?? 'Cash'))),
              const SizedBox(width: 10),
              Expanded(child: TextField(controller: ref_,
                  decoration: const InputDecoration(labelText: 'Reference (voucher no.)', isDense: true, border: OutlineInputBorder()))),
            ]),
          ]),
        ),
        actions: [
          TextButton(onPressed: () => Navigator.pop(ctx), child: const Text('Cancel')),
          ElevatedButton(
            onPressed: busy ? null : () async {
              final a = num.tryParse(amt.text.trim());
              if (a == null) { _snack('Enter the amount paid'); return; }
              setS(() => busy = true);
              try {
                await _db.rpc('reimb_mark_paid', params: {
                  'p_claim': c['id'], 'p_amount': a, 'p_paid_on': DateFormat('yyyy-MM-dd').format(on),
                  'p_method': method, 'p_ref': ref_.text.trim(),
                });
                if (ctx.mounted) Navigator.pop(ctx);
                _snack('Marked paid');
                await _load();
              } catch (e) {
                setS(() => busy = false);
                _snack(friendlyError('Could not save', e));
              }
            },
            child: const Text('Mark paid'),
          ),
        ],
      )),
    );
  }

  // ── print ─────────────────────────────────────────────────────────────────
  void _printList(List<Map<String, dynamic>> list) {
    final b = StringBuffer()
      ..write('<h1>Reimbursement Approvals</h1><div class="meta">${list.length} claims</div>')
      ..write('<table><tr><th>Person</th><th>Document</th><th>Dates</th><th class="num">Distance</th><th class="num">Amount</th><th>Status</th><th>Approved by</th><th>Paid</th></tr>');
    for (final c in list) {
      final amt = _amount(c);
      b.write('<tr><td><b>${esc(c['claimant_name'])}</b></td>'
          '<td>${c['doc_type'] == 'combined_summary' ? 'Combined Trip Summary' : 'Trip Summary'}</td>'
          '<td>${esc(_dates(c))}</td><td class="num">${esc(_km(c['km'] as num?))}</td>'
          '<td class="num">${amt == null ? '' : esc(_rs(amt))}</td><td>${esc(_pill('${c['status']}').$1)}</td>'
          '<td>${esc(c['decided_by_name'])}</td>'
          '<td>${c['status'] == 'paid' ? esc('${_fd(c['paid_on'])} ${c['paid_method'] ?? ''} ${c['paid_ref'] ?? ''}') : ''}</td></tr>');
    }
    b.write('</table>');
    openPrint('Reimbursement Approvals', b.toString());
  }
