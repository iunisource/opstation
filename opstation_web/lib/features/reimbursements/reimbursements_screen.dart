  Future<void> _printAdjustedCombined(Map<String, dynamic> c) => withGenerating(context, () => _printAdjustedCombinedRun(c));

  Future<void> _printAdjustedCombinedRun(Map<String, dynamic> c) async {
    try {
      final lines = _lines[c['id']] ?? const <Map<String, dynamic>>[];
      final tripIds = [for (final l in lines) if ((l['trip_id'] ?? '') != '') '${l['trip_id']}'];
      final routes = <String, String>{};
      if (tripIds.isNotEmpty) {
        for (final t in await _db.from('trips').select('id, route_name').inFilter('id', tripIds)) {
          routes['${t['id']}'] = '${t['route_name'] ?? ''}';
        }
      }
      final adj = _adj[c['id']] ?? const {};
      final byDay = <String, List<Map<String, dynamic>>>{};
      for (final l in lines) {
        (byDay['${l['day']}'.substring(0, 10)] ??= []).add(l);
      }
      final days = byDay.keys.toList()..sort();
      final rows = <CombinedSummaryRow>[
        for (final d in days)
          CombinedSummaryRow(
            date: DateTime.parse(d),
            salesperson: '${c['claimant_name'] ?? ''}',
            routes: [
              for (final l in byDay[d]!)
                '${routes['${l['trip_id']}'] ?? ''}${adj['${l['trip_id']}'] != null ? ' (adjusted)' : ''}'.trim(),
            ].where((x) => x.isNotEmpty).join(', '),
            km: byDay[d]!.fold<double>(0, (s, l) => s + ((l['km'] as num?) ?? 0).toDouble()),
          ),
      ];
      final total = rows.fold<double>(0, (s, r) => s + r.km);
      final notes = [
        for (final l in lines)
          if (adj['${l['trip_id']}'] != null)
            reimbAdjustNote(adj['${l['trip_id']}']!, dayLabel: _fd(l['day'], 'EEE d MMM'), reasons: false,
                defaultAllowance: _allowDefault),
      ];
      final bytes = await ReportPdfBuilder.buildCombinedTripSummary(
        orgName: ref.read(currentUserProvider)?.orgName ?? 'Opstation',
        periodLabel: _dates(c).replaceAll('–', '-'), // PDF font has no en dash
        salespersonLabel: '${c['claimant_name'] ?? ''}',
        showSalesperson: false,
        rows: rows,
        grandTotalKm: total,
        reimb: () {
          // "6 days × Rs 150" when every day has the default or none; else the total.
          final days = {for (final l in lines) '${l['day']}'.substring(0, 10)};
          final vals = [for (final d in days) _dayAllowance(c, d)].whereType<double>().toList();
          final atDefault = vals.where((v) => (v - _allowDefault).abs() < 0.005).length;
          return ReimbInfo(
            rate: (c['rate'] as num?)?.toDouble() ?? _rate,
            allowancePerDay: _allowDefault > 0 ? _allowDefault : null,
            unpaidDays: atDefault,
            allowanceTotal: _allowance(c) > 0 || _allowDefault > 0 ? _allowance(c) : null,
            approvedBy: c['status'] == 'approved' || c['status'] == 'paid' ? '${c['decided_by_name'] ?? ''}' : null,
            approvedAt: DateTime.tryParse('${c['decided_at'] ?? ''}'),
            verifyUrl: _verifyUrl(c),
          );
        }(),
        adjustNote: notes.isEmpty ? null : notes.join('\n'),
      );
      await outputPdf(bytes, notes.isEmpty ? 'Combined Trip Summary' : 'Combined Trip Summary (adjusted)');
    } catch (e) {
      _snack(friendlyError('Could not print', e));
    }
  }

  /// Public check link printed as a QR under the signature (SQL 485).
  String? _verifyUrl(Map c) {
    final t = '${c['public_token'] ?? ''}';
    return t.length < 32 ? null : '${Uri.base.origin}/#/rc/$t';
  }

