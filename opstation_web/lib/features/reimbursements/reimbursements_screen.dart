  void _openAdvice(Map c) {
    if (c['advice_id'] == null) return;
    GoRouter.of(context).go('/financials/payment-advice?focus=${c['advice_id']}');
  }

  // ── actions ───────────────────────────────────────────────────────────────
  Future<void> _approve(Map c) async {
    try {
      await _db.rpc('reimb_decide', params: {'p_claim': c['id'], 'p_approve': true});
      _snack(_paMode ? 'Approved — Payment Advice created' : 'Approved — ${c['claimant_name'] ?? ''}');
      await _load();
    } catch (e) {
      _snack(friendlyError('Could not approve', e));
    }
  }

  Future<void> _reject(Map c) async {
    final reason = TextEditingController();
    final ok = await showDialog<bool>(
      context: context,
      builder: (d) => AlertDialog(
        title: Text('Reject — ${c['claimant_name'] ?? ''}'),
        content: SizedBox(
          width: 400,
          child: TextField(controller: reason, autofocus: true, maxLines: 2,
              decoration: const InputDecoration(labelText: 'Reason *', border: OutlineInputBorder())),
        ),
        actions: [
          TextButton(onPressed: () => Navigator.pop(d, false), child: const Text('Cancel')),
          ElevatedButton(onPressed: () => Navigator.pop(d, true), child: const Text('Reject')),
        ],
      ),
    );
    if (ok != true) return;
    if (reason.text.trim().isEmpty) { _snack('Enter the reason'); return; }
    try {
      await _db.rpc('reimb_decide', params: {'p_claim': c['id'], 'p_approve': false, 'p_reason': reason.text.trim()});
      _snack('Rejected');
      await _load();
    } catch (e) {
      _snack(friendlyError('Could not reject', e));
    }
  }

  Future<void> _markPaid(Map c) async {
    final amt = TextEditingController(text: c['amount'] == null ? '' : '${(c['amount'] as num).round()}');
    final ref_ = TextEditingController();
    String method = 'Cash';
    DateTime on = DateTime.now();
    var busy = false;
    await showDialog<void>(
      context: context,
      builder: (ctx) => StatefulBuilder(builder: (ctx, setS) => AlertDialog(
        title: Text('Mark paid — ${c['claimant_name'] ?? ''}'),
        content: SizedBox(
          width: 420,
          child: Column(mainAxisSize: MainAxisSize.min, children: [
            Text('${_dates(c)} · ${_km(_unpaidKm(c))}', style: const TextStyle(fontSize: 12.5, color: AppTheme.textSecondary)),
            const SizedBox(height: 12),
            Row(children: [
              Expanded(child: TextField(
                controller: amt, autofocus: true,
                keyboardType: const TextInputType.numberWithOptions(decimal: true),
                inputFormatters: [FilteringTextInputFormatter.allow(RegExp(r'[0-9.]'))],
                decoration: const InputDecoration(labelText: 'Amount paid (Rs) *', isDense: true, border: OutlineInputBorder()))),
              const SizedBox(width: 10),
              Expanded(child: InkWell(
                onTap: () async {
                  final p = await showDatePicker(context: ctx, initialDate: on, firstDate: DateTime(2020), lastDate: DateTime.now().add(const Duration(days: 30)));
                  if (p != null) setS(() => on = p);
                },
                child: InputDecorator(decoration: const InputDecoration(labelText: 'Paid on', isDense: true, border: OutlineInputBorder()),
                    child: Text(DateFormat('d MMM yyyy').format(on))),
              )),
            ]),
            const SizedBox(height: 10),
            Row(children: [
              Expanded(child: DropdownButtonFormField<String>(
                value: method, isExpanded: true,
                decoration: const InputDecoration(labelText: 'Method', isDense: true, border: OutlineInputBorder()),
                items: [for (final m in const ['Cash', 'Bank transfer', 'Cheque', 'With salary']) DropdownMenuItem(value: m, child: Text(m))],
                onChanged: (v) => setS(() => method = v ?? 'Cash'))),
              const SizedBox(width: 10),
              Expanded(child: TextField(controller: ref_,
                  decoration: const InputDecoration(labelText: 'Reference (voucher no.)', isDense: true, border: OutlineInputBorder()))),
            ]),
          ]),
        ),
        actions: [
          TextButton(onPressed: () => Navigator.pop(ctx), child: const Text('Cancel')),
          ElevatedButton(
            onPressed: busy ? null : () async {
              final a = num.tryParse(amt.text.trim());
              if (a == null) { _snack('Enter the amount paid'); return; }
              setS(() => busy = true);
              try {
                await _db.rpc('reimb_mark_paid', params: {
                  'p_claim': c['id'], 'p_amount': a, 'p_paid_on': DateFormat('yyyy-MM-dd').format(on),
                  'p_method': method, 'p_ref': ref_.text.trim(),
                });
                if (ctx.mounted) Navigator.pop(ctx);
                _snack('Marked paid');
                await _load();
              } catch (e) {
                setS(() => busy = false);
                _snack(friendlyError('Could not save', e));
              }
            },
            child: const Text('Mark paid'),
          ),
        ],
      )),
    );
  }

  // ── print ─────────────────────────────────────────────────────────────────
  void _printList(List<Map<String, dynamic>> list) {
    final b = StringBuffer()
      ..write('<h1>Reimbursement Approvals</h1><div class="meta">${list.length} claims</div>')
      ..write('<table><tr><th>Person</th><th>Document</th><th>Dates</th><th class="num">Distance</th><th class="num">Amount</th><th>Status</th><th>Approved by</th><th>Paid</th></tr>');
    for (final c in list) {
      final amt = _amount(c);
      b.write('<tr><td><b>${esc(c['claimant_name'])}</b></td>'
          '<td>${c['doc_type'] == 'combined_summary' ? 'Combined Trip Summary' : 'Trip Summary'}</td>'
          '<td>${esc(_dates(c))}</td><td class="num">${esc(_km(c['km'] as num?))}</td>'
          '<td class="num">${amt == null ? '' : esc(_rs(amt))}</td><td>${esc(_pill('${c['status']}').$1)}</td>'
          '<td>${esc(c['decided_by_name'])}</td>'
          '<td>${c['status'] == 'paid' ? esc('${_fd(c['paid_on'])} ${c['paid_method'] ?? ''} ${c['paid_ref'] ?? ''}') : ''}</td></tr>');
    }
    b.write('</table>');
    openPrint('Reimbursement Approvals', b.toString());
  }
