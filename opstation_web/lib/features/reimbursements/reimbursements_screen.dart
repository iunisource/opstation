SupabaseClient get _db => Supabase.instance.client;

String _fd(dynamic v, [String f = 'd MMM yyyy']) {
  final d = DateTime.tryParse('${v ?? ''}');
  return d == null ? '—' : DateFormat(f).format(d.toLocal());
}

String _rs(num? v) => v == null ? '—' : 'Rs ${NumberFormat('#,##0').format(v)}';
String _km(num? v) => '${NumberFormat('#,##0.0').format(v ?? 0)} km';

(String, Color, Color) _pill(String s) => switch (s) {
      'approved' => ('Approved · to pay', const Color(0xFF1D4ED8), const Color(0xFFEFF6FF)),
      'paid' => ('Paid', const Color(0xFF047857), const Color(0xFFECFDF5)),
      'rejected' => ('Rejected', const Color(0xFFB91C1C), const Color(0xFFFEF2F2)),
      _ => ('Pending', const Color(0xFFB45309), const Color(0xFFFFFBEB)),
    };

/// Operations → Reimbursement Approvals (SQL 466). Trip Summaries / Combined
/// Trip Summaries generated by drivers and salespersons land here; approvers
/// approve, accounts mark paid. Generating summaries works as before.
class ReimbursementsScreen extends ConsumerStatefulWidget {
  final String? openId;
  const ReimbursementsScreen({super.key, this.openId});
  @override
  ConsumerState<ReimbursementsScreen> createState() => _ReimbursementsScreenState();
}

class _ReimbursementsScreenState extends ConsumerState<ReimbursementsScreen> {
  List<Map<String, dynamic>> _claims = [];
  final Map<String, List<Map<String, dynamic>>> _lines = {};
  final Map<String, Map<String, dynamic>> _paidTrips = {}; // trip id -> {claim_id, paid_on}
  Map<String, String> _roles = {};
  bool _loading = true, _missing = false, _canApprove = false, _canPay = false;
  double? _rate;
  bool _paMode = false; // Admin Settings: approving creates a Payment Advice
  String _tab = 'pending';
  String _q = '';
  bool _openedLink = false;

  String? get _org => ref.read(currentUserProvider)?.orgId;

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addPostFrameCallback((_) => _load());
  }

  void _snack(String m) => ScaffoldMessenger.maybeOf(context)?.showSnackBar(SnackBar(content: Text(m)));

  Future<void> _load() async {
    final org = _org;
    if (org == null) return;
    try {
      final r = await Future.wait<dynamic>([
        _db.from('reimb_claims').select().eq('org_id', org).order('last_generated_at', ascending: false).limit(1000),
        _db.from('reimb_lines').select('claim_id, trip_id, day, km').eq('org_id', org).limit(20000),
        _db.from('reimb_trip_paid').select('trip_id, claim_id, paid_on').eq('org_id', org).limit(20000),
        _db.rpc('reimb_can_approve', params: {'p_org': org}),
        _db.rpc('reimb_can_pay', params: {'p_org': org}),
        _db.from('app_config').select('key, value').eq('org_id', org)
            .inFilter('key', ['org.reimb_rate_km', 'org.reimb_after_approval']).isFilter('branch_id', null),
        _db.from('users').select('id, role').eq('org_id', org),
      ]);
      if (!mounted) return;
      _lines.clear();
      for (final l in r[1] as List) {
        _lines.putIfAbsent('${l['claim_id']}', () => []).add(Map<String, dynamic>.from(l as Map));
      }
      for (final ls in _lines.values) {
        ls.sort((a, b) => '${a['day']}'.compareTo('${b['day']}'));
      }
      _paidTrips
        ..clear()
        ..addAll({for (final p in r[2] as List) '${p['trip_id']}': Map<String, dynamic>.from(p as Map)});
      final cfg = {for (final x in r[5] as List) '${x['key']}': '${x['value'] ?? ''}'.trim()};
      final rate = double.tryParse(cfg['org.reimb_rate_km'] ?? '');
      final paMode = cfg['org.reimb_after_approval'] == 'payment_advice';
      setState(() {
        _claims = List<Map<String, dynamic>>.from(r[0] as List);
        _canApprove = r[3] == true;
        _canPay = r[4] == true;
        _rate = rate != null && rate > 0 ? rate : null;
        _paMode = paMode;
        _roles = {for (final u in r[6] as List) '${u['id']}': '${u['role'] ?? ''}'};
        _loading = false;
        _missing = false;
      });
      ref.invalidate(reimbTodoCountProvider);
      if (!_openedLink && widget.openId != null) {
        _openedLink = true;
        final c = _claims.where((x) => x['id'] == widget.openId).firstOrNull;
        if (c != null) {
          setState(() => _tab = 'all');
          _open(c);
        }
      }
    } catch (_) {
      if (mounted) setState(() { _loading = false; _missing = true; });
    }
  }

  static int _dayCount(List<Map<String, dynamic>> ls) => ls.map((l) => '${l['day']}').toSet().length;

  // ── figures ───────────────────────────────────────────────────────────────
  /// Lines of [c] already paid on ANOTHER claim.
  List<Map<String, dynamic>> _paidElsewhere(Map c) => (_lines[c['id']] ?? const [])
      .where((l) => _paidTrips[l['trip_id']] != null && _paidTrips[l['trip_id']]!['claim_id'] != c['id'])
      .toList();

  double _unpaidKm(Map c) {
    if (c['unpaid_km'] != null && c['status'] != 'pending') return (c['unpaid_km'] as num).toDouble();
    final pe = {for (final l in _paidElsewhere(c)) l['trip_id']};
    return (_lines[c['id']] ?? const [])
        .where((l) => !pe.contains(l['trip_id']))
        .fold<double>(0, (s, l) => s + ((l['km'] as num?) ?? 0).toDouble());
  }

  num? _amount(Map c) {
    if (c['status'] == 'paid') return c['paid_amount'] as num?;
    if (c['status'] != 'pending' && c['amount'] != null) return c['amount'] as num;
    return _rate == null ? null : (_unpaidKm(c) * _rate!).round();
  }

  String _dates(Map c) {
    final a = DateTime.tryParse('${c['date_from'] ?? ''}');
    final b = DateTime.tryParse('${c['date_to'] ?? ''}');
    if (a == null) return '—';
    if (b == null || a == b) return DateFormat('d MMM yyyy').format(a);
    if (a.year == b.year && a.month == b.month) return '${a.day} – ${DateFormat('d MMM yyyy').format(b)}';
    return '${DateFormat('d MMM').format(a)} – ${DateFormat('d MMM yyyy').format(b)}';
  }

  String _role(Map c) => switch (_roles[c['claimant_id']]) {
        'driver' => 'Driver',
        'salesperson' => 'Salesperson',
        final r? when r.isNotEmpty => r[0].toUpperCase() + r.substring(1),
        _ => '',
      };

  List<Map<String, dynamic>> get _shown => _claims.where((c) {
        if (_tab != 'all' && c['status'] != _tab) return false;
        if (_q.isNotEmpty) {
          final s = '${c['claimant_name']} ${c['paid_ref'] ?? ''}'.toLowerCase();
          if (!s.contains(_q.toLowerCase())) return false;
        }
        return true;
      }).toList();

  // ── UI ────────────────────────────────────────────────────────────────────
  @override
  Widget build(BuildContext context) {
    final wide = MediaQuery.of(context).size.width >= 900;
    int n(String s) => _claims.where((c) => c['status'] == s).length;
    final now = DateTime.now();
    final paidMonth = _claims
        .where((c) {
          final d = DateTime.tryParse('${c['paid_on'] ?? ''}');
          return c['status'] == 'paid' && d != null && d.year == now.year && d.month == now.month;
        })
        .fold<num>(0, (s, c) => s + ((c['paid_amount'] as num?) ?? 0));
    final list = _shown;
    return Container(
      color: AppTheme.background,
      padding: EdgeInsets.all(wide ? 24 : 12),
      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
        Wrap(spacing: 8, runSpacing: 8, crossAxisAlignment: WrapCrossAlignment.center, children: [
          Text('Reimbursement Approvals', style: TextStyle(fontSize: wide ? 24 : 20, fontWeight: FontWeight.w800)),
          const SizedBox(width: 4),
          _chip('${n('pending')}', 'pending approval', const Color(0xFFB45309)),
          _chip('${n('approved')}', 'approved · to pay', const Color(0xFF1D4ED8)),
          _chip(_rs(paidMonth), 'paid this month', const Color(0xFF047857)),
          const SizedBox(width: 8),
          OutlinedButton.icon(onPressed: list.isEmpty ? null : () => _printList(list), icon: const Icon(Icons.print_outlined, size: 16), label: const Text('Print / PDF')),
          IconButton(tooltip: 'Refresh', onPressed: _load, icon: const Icon(Icons.refresh, size: 20)),
        ]),
        const SizedBox(height: 10),
        SingleChildScrollView(
          scrollDirection: Axis.horizontal,
          child: Row(children: [
            for (final t in const [('pending', 'Pending approval'), ('approved', 'Approved · to pay'), ('paid', 'Paid'), ('rejected', 'Rejected'), ('all', 'All')])
              Padding(
                padding: const EdgeInsets.only(right: 6),
                child: ChoiceChip(
                  label: Text(t.$1 == 'all' ? t.$2 : '${t.$2} (${n(t.$1)})'),
                  selected: _tab == t.$1,
                  onSelected: (_) => setState(() => _tab = t.$1),
                ),
              ),
          ]),
        ),
        const SizedBox(height: 10),
        SizedBox(
          width: 260,
          child: TextField(
            decoration: const InputDecoration(isDense: true, hintText: 'Search person or reference…', prefixIcon: Icon(Icons.search, size: 18)),
            onChanged: (v) => setState(() => _q = v.trim()),
          ),
        ),
        const SizedBox(height: 10),
        Expanded(
          child: _loading
              ? const Center(child: CircularProgressIndicator())
              : _missing
                  ? const Center(child: Text('Run SQL 466 to set up Reimbursement Approvals.', style: TextStyle(color: AppTheme.textSecondary)))
                  : list.isEmpty
                      ? Center(
                          child: Text(
                            _claims.isEmpty
                                ? 'No trip summaries yet. They appear here when a driver or salesperson generates one\n'
                                    '(Admin Settings → Reimbursement approvals must be on).'
                                : 'Nothing here.',
                            textAlign: TextAlign.center,
                            style: const TextStyle(color: AppTheme.textSecondary)))
                      : ListView(children: [for (final c in list) _row(c, wide)]),
        ),
      ]),
    );
  }

  Widget _chip(String v, String l, Color c) => Container(
        padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 5),
        decoration: BoxDecoration(color: c.withOpacity(0.07), borderRadius: BorderRadius.circular(8), border: Border.all(color: c.withOpacity(0.3))),
        child: Text.rich(TextSpan(style: TextStyle(fontSize: 12, color: c), children: [
          TextSpan(text: v, style: const TextStyle(fontWeight: FontWeight.w800, fontSize: 13)),
          TextSpan(text: '  $l'),
        ])),
      );

  Widget _statusPill(Map c) {
    final pe = c['status'] == 'pending' && _paidElsewhere(c).isNotEmpty;
    final p = pe ? ('Partly paid before', const Color(0xFF6D28D9), const Color(0xFFF5F3FF)) : _pill('${c['status']}');
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 2),
      decoration: BoxDecoration(color: p.$3, borderRadius: BorderRadius.circular(999)),
      child: Text(p.$1, style: TextStyle(fontSize: 11, fontWeight: FontWeight.w700, color: p.$2)),
    );
  }

  Widget? _action(Map<String, dynamic> c) {
    if (c['status'] == 'pending' && _canApprove) {
      return ElevatedButton(
        style: ElevatedButton.styleFrom(backgroundColor: const Color(0xFF059669), foregroundColor: Colors.white, visualDensity: VisualDensity.compact),
        onPressed: () => _approve(c),
        child: const Text('Approve'),
      );
    }
    if (c['advice_id'] != null && c['status'] == 'approved') {
      return TextButton(
        style: TextButton.styleFrom(visualDensity: VisualDensity.compact),
        onPressed: () => _openAdvice(c),
        child: Text('${c['advice_number'] ?? 'Payment Advice'}'),
      );
    }
    if (c['status'] == 'approved' && _canPay) {
      return ElevatedButton(
        style: ElevatedButton.styleFrom(visualDensity: VisualDensity.compact),
        onPressed: () => _markPaid(c),
        child: const Text('Mark paid'),
      );
    }
    return null;
  }

  Widget _row(Map<String, dynamic> c, bool wide) {
    final pe = _paidElsewhere(c);
    final amt = _amount(c);
    final person = Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      Text('${c['claimant_name'] ?? '—'}', style: const TextStyle(fontWeight: FontWeight.w700, fontSize: 13.5)),
      if (_role(c).isNotEmpty) Text(_role(c), style: const TextStyle(fontSize: 11.5, color: AppTheme.textSecondary)),
    ]);
    final doc = Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      Text(c['doc_type'] == 'combined_summary' ? 'Combined Trip Summary' : 'Trip Summary', style: const TextStyle(fontSize: 12.5)),
      Text('${c['trips']} trip${c['trips'] == 1 ? '' : 's'}', style: const TextStyle(fontSize: 11.5, color: AppTheme.textSecondary)),
    ]);
    final money = Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      Text(amt == null ? '—' : _rs(amt), style: const TextStyle(fontWeight: FontWeight.w700, fontSize: 13)),
      Text(pe.isNotEmpty && c['status'] == 'pending'
              ? '${_dayCount(pe)} day(s) already paid'
              : (c['status'] == 'paid' ? 'paid ${_fd(c['paid_on'], 'd MMM')}' : (_rate == null || c['status'] == 'rejected' ? '' : '@ Rs ${NumberFormat('#,##0.##').format(c['rate'] ?? _rate)}/km')),
          style: const TextStyle(fontSize: 11.5, color: AppTheme.textSecondary)),
    ]);
    final gen = Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      Text(_fd(c['first_generated_at'], 'd MMM, h:mm a'), style: const TextStyle(fontSize: 12.5)),
      Text([if ((c['generated_by_name'] ?? '') != '') 'by ${c['generated_by_name']}', if ((c['generated_count'] ?? 1) > 1) 'generated ${c['generated_count']}×'].join(' · '),
          style: const TextStyle(fontSize: 11.5, color: AppTheme.textSecondary)),
    ]);
    final action = _action(c);
    return Card(
      elevation: 0,
      margin: const EdgeInsets.only(bottom: 8),
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12), side: const BorderSide(color: AppTheme.border)),
      child: InkWell(
        borderRadius: BorderRadius.circular(12),
        onTap: () => _open(c),
        child: Padding(
          padding: const EdgeInsets.all(12),
          child: wide
              ? Row(children: [
                  Expanded(flex: 3, child: person),
                  Expanded(flex: 3, child: doc),
                  Expanded(flex: 3, child: Text(_dates(c), style: const TextStyle(fontSize: 12.5))),
                  Expanded(flex: 2, child: Text(_km(c['km'] as num?), style: const TextStyle(fontSize: 12.5))),
                  Expanded(flex: 3, child: money),
                  Expanded(flex: 3, child: gen),
                  SizedBox(width: 140, child: Align(alignment: Alignment.centerLeft, child: _statusPill(c))),
                  SizedBox(width: 100, child: Align(alignment: Alignment.centerRight, child: action ?? const SizedBox())),
                ])
              : Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                  Row(children: [Expanded(child: person), _statusPill(c)]),
                  const SizedBox(height: 6),
                  Wrap(spacing: 16, runSpacing: 6, children: [
                    doc,
                    Text('${_dates(c)}\n${_km(c['km'] as num?)}', style: const TextStyle(fontSize: 12)),
                    money,
                  ]),
                  if (action != null) ...[const SizedBox(height: 8), Align(alignment: Alignment.centerRight, child: action)],
                ]),
        ),
      ),
    );
  }

  // ── claim page ────────────────────────────────────────────────────────────
  Future<void> _open(Map<String, dynamic> c) async {
    final lines = _lines[c['id']] ?? const <Map<String, dynamic>>[];
    final pe = _paidElsewhere(c);
    final peDays = {for (final l in pe) _fd(l['day'], 'd MMM')};
    final peRefs = {
      for (final l in pe)
        () {
          final p = _paidTrips[l['trip_id']]!;
          final oc = _claims.where((x) => x['id'] == p['claim_id']).firstOrNull;
          return 'paid ${_fd(p['paid_on'])}${(oc?['paid_ref'] ?? '') != '' ? ' — ${oc!['paid_ref']}' : ''}';
        }(),
    };
    final amt = _amount(c);
    await showDialog<void>(
      context: context,
      builder: (ctx) => Dialog(
        insetPadding: const EdgeInsets.all(16),
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
        child: ConstrainedBox(
          constraints: BoxConstraints(maxWidth: 760, maxHeight: MediaQuery.of(ctx).size.height * 0.9),
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(18),
            child: Column(mainAxisSize: MainAxisSize.min, crossAxisAlignment: CrossAxisAlignment.start, children: [
              Wrap(spacing: 8, runSpacing: 8, crossAxisAlignment: WrapCrossAlignment.center, children: [
                Text('${c['claimant_name'] ?? ''} · ${_dates(c)}', style: const TextStyle(fontSize: 19, fontWeight: FontWeight.w800)),
                _statusPill(c),
              ]),
              const SizedBox(height: 10),
              Wrap(spacing: 8, runSpacing: 8, children: [
                if (c['status'] == 'pending' && _canApprove) ...[
                  OutlinedButton.icon(
                    onPressed: () async { Navigator.pop(ctx); await _reject(c); },
                    style: OutlinedButton.styleFrom(foregroundColor: AppTheme.danger),
                    icon: const Icon(Icons.close, size: 16), label: const Text('Reject')),
                  ElevatedButton.icon(
                    onPressed: () async { Navigator.pop(ctx); await _approve(c); },
                    style: ElevatedButton.styleFrom(backgroundColor: const Color(0xFF059669), foregroundColor: Colors.white),
                    icon: const Icon(Icons.check, size: 16),
                    label: Text(_paMode
                        ? 'Approve & create Payment Advice${amt == null ? '' : ' (${_rs(amt)})'}'
                        : (amt == null ? 'Approve' : 'Approve ${_rs(amt)}'))),
                ],
                if (c['status'] == 'rejected' && _canApprove)
                  OutlinedButton.icon(
                    onPressed: () async { Navigator.pop(ctx); await _approve(c); },
                    icon: const Icon(Icons.check, size: 16), label: const Text('Approve after all')),
                if (c['advice_id'] != null)
                  OutlinedButton.icon(
                    onPressed: () { Navigator.pop(ctx); _openAdvice(c); },
                    icon: const Icon(Icons.description_outlined, size: 16),
                    label: Text('Open ${c['advice_number'] ?? 'Payment Advice'}')),
                if (c['status'] == 'approved' && _canPay && c['advice_id'] == null)
                  ElevatedButton.icon(
                    onPressed: () async { Navigator.pop(ctx); await _markPaid(c); },
                    icon: const Icon(Icons.payments_outlined, size: 16), label: const Text('Mark paid')),
              ]),
              if (pe.isNotEmpty && c['status'] != 'paid') ...[
                const SizedBox(height: 12),
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(10),
                  decoration: BoxDecoration(color: const Color(0xFFFFF7ED), borderRadius: BorderRadius.circular(8), border: Border.all(color: const Color(0xFFFED7AA))),
                  child: Text(
                    '${peDays.length} of these days (${peDays.join(', ')}) were already paid (${peRefs.join('; ')}). '
                    'They are left out of the amount.',
                    style: const TextStyle(fontSize: 12.5, color: Color(0xFF9A3412))),
                ),
              ],
              if (c['status'] == 'pending' && (c['note'] ?? '') != '') ...[
                const SizedBox(height: 12),
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(10),
                  decoration: BoxDecoration(color: const Color(0xFFFEF2F2), borderRadius: BorderRadius.circular(8)),
                  child: Text('${c['note']}', style: const TextStyle(fontSize: 12.5, color: Color(0xFFB91C1C))),
                ),
              ],
              if (c['status'] == 'approved' && c['advice_id'] != null) ...[
                const SizedBox(height: 12),
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(10),
                  decoration: BoxDecoration(color: const Color(0xFFEFF6FF), borderRadius: BorderRadius.circular(8)),
                  child: Text('Payment Advice ${c['advice_number'] ?? ''} was created. This claim turns Paid when that advice is marked paid.',
                      style: const TextStyle(fontSize: 12.5, color: Color(0xFF1D4ED8))),
                ),
              ],
              if (c['status'] == 'rejected' && (c['reject_reason'] ?? '') != '') ...[
                const SizedBox(height: 12),
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(10),
                  decoration: BoxDecoration(color: const Color(0xFFFEF2F2), borderRadius: BorderRadius.circular(8)),
                  child: Text('Rejected by ${c['decided_by_name'] ?? '—'}: ${c['reject_reason']}', style: const TextStyle(fontSize: 12.5, color: Color(0xFFB91C1C))),
                ),
              ],
              const SizedBox(height: 12),
              _box(Wrap(spacing: 24, runSpacing: 10, children: [
                _kv('Document', c['doc_type'] == 'combined_summary' ? 'Combined Trip Summary' : 'Trip Summary'),
                if (_role(c).isNotEmpty) _kv('Role', _role(c)),
                _kv('Distance', _km(c['km'] as num?)),
                if (pe.isNotEmpty) _kv('Unpaid distance', _km(_unpaidKm(c))),
                _kv('Rate', c['rate'] != null ? 'Rs ${NumberFormat('#,##0.##').format(c['rate'])} / km' : (_rate == null ? '—' : 'Rs ${NumberFormat('#,##0.##').format(_rate)} / km')),
                _kv(c['status'] == 'paid' ? 'Paid' : 'Amount', amt == null ? '—' : _rs(amt)),
                if (c['advice_number'] != null) _kv('Payment Advice', '${c['advice_number']}'),
                _kv('Generated', '${c['generated_count'] ?? 1}×'),
                _kv('First generated', _fd(c['first_generated_at'], 'd MMM, h:mm a')),
                if (c['decided_at'] != null) _kv(c['status'] == 'rejected' ? 'Rejected by' : 'Approved by', '${c['decided_by_name'] ?? '—'} · ${_fd(c['decided_at'], 'd MMM')}'),
                if (c['status'] == 'paid') ...[
                  _kv('Paid on', _fd(c['paid_on'])),
                  _kv('Method', '${c['paid_method'] ?? '—'}'),
                  _kv('Reference', '${c['paid_ref'] ?? '—'}'),
                  _kv('Marked paid by', '${c['paid_by_name'] ?? '—'}'),
                ],
              ])),
              _box(Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('Days (${_dayCount(lines)})', style: const TextStyle(fontWeight: FontWeight.w700)),
                const SizedBox(height: 6),
                for (final l in lines)
                  Padding(
                    padding: const EdgeInsets.symmetric(vertical: 3),
                    child: Row(children: [
                      SizedBox(width: 120, child: Text(_fd(l['day'], 'EEE, d MMM'), style: const TextStyle(fontSize: 12.5))),
                      SizedBox(width: 90, child: Text(_km(l['km'] as num?), style: const TextStyle(fontSize: 12.5))),
                      () {
                        final p = _paidTrips[l['trip_id']];
                        if (p == null) {
                          return Text(c['status'] == 'rejected' ? '' : 'Unpaid', style: const TextStyle(fontSize: 11.5, color: Color(0xFFB45309), fontWeight: FontWeight.w600));
                        }
                        final own = p['claim_id'] == c['id'];
                        return Text(own ? 'Paid ${_fd(p['paid_on'], 'd MMM')}' : 'Paid ${_fd(p['paid_on'], 'd MMM')} (earlier claim)',
                            style: const TextStyle(fontSize: 11.5, color: Color(0xFF047857), fontWeight: FontWeight.w600));
                      }(),
                    ]),
                  ),
              ])),
            ]),
          ),
        ),
      ),
    );
  }

  Widget _box(Widget child) => Container(
        width: double.infinity,
        margin: const EdgeInsets.only(bottom: 10),
        padding: const EdgeInsets.all(12),
        decoration: BoxDecoration(color: Colors.white, borderRadius: BorderRadius.circular(12), border: Border.all(color: AppTheme.border)),
        child: child,
      );

  Widget _kv(String k, String v) => SizedBox(
        width: 170,
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Text(k, style: const TextStyle(fontSize: 11, color: AppTheme.textSecondary)),
          Text(v, style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600)),
