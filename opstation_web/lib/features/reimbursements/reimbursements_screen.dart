  void _snack(String m) => ScaffoldMessenger.maybeOf(context)?.showSnackBar(SnackBar(content: Text(m)));

  Future<void> _load() async {
    final org = _org;
    if (org == null) return;
    try {
      final r = await Future.wait<dynamic>([
        _db.from('reimb_claims').select().eq('org_id', org).order('last_generated_at', ascending: false).limit(1000),
        _db.from('reimb_lines').select('claim_id, trip_id, day, km').eq('org_id', org).limit(20000),
        _db.from('reimb_trip_paid').select('trip_id, claim_id, paid_on').eq('org_id', org).limit(20000),
        _db.rpc('reimb_can_approve', params: {'p_org': org}),
        _db.rpc('reimb_can_pay', params: {'p_org': org}),
        _db.from('app_config').select('key, value, branch_id').eq('org_id', org)
            .inFilter('key', ['org.reimb_rate_km', 'org.reimb_after_approval', 'org.reimb_allowance_print', 'org.reimb_allowance_day']),
        _db.from('users').select('id, role').eq('org_id', org),
      ]);
      if (!mounted) return;
      _adj.clear();
      try {
        for (final a in await _db.from('reimb_adjustments').select().eq('org_id', org).limit(20000)) {
          (_adj['${a['claim_id']}'] ??= {})['${a['trip_id']}'] = Map<String, dynamic>.from(a);
        }
      } catch (_) {} // SQL 478 not run yet
      _lines.clear();
      for (final l in r[1] as List) {
        _lines.putIfAbsent('${l['claim_id']}', () => []).add(Map<String, dynamic>.from(l as Map));
      }
      for (final ls in _lines.values) {
        ls.sort((a, b) => '${a['day']}'.compareTo('${b['day']}'));
      }
      _paidTrips
        ..clear()
        ..addAll({for (final p in r[2] as List) '${p['trip_id']}': Map<String, dynamic>.from(p as Map)});
      // The org-wide row (no branch) wins; a row saved with a branch is used otherwise.
      final cfg = <String, String>{};
      final rows = [for (final x in r[5] as List) Map<String, dynamic>.from(x as Map)]
        ..sort((a, b) => (a['branch_id'] == null ? 1 : 0).compareTo(b['branch_id'] == null ? 1 : 0));
      for (final x in rows) {
        final v = '${x['value'] ?? ''}'.trim();
        if (v.isNotEmpty) cfg['${x['key']}'] = v; // later (org-wide) rows overwrite branch rows
      }
      final rate = double.tryParse(cfg['org.reimb_rate_km'] ?? '');
      final paMode = cfg['org.reimb_after_approval'] == 'payment_advice';
      setState(() {
        _claims = List<Map<String, dynamic>>.from(r[0] as List);
        _canApprove = r[3] == true;
        _canPay = r[4] == true;
        _rate = rate != null && rate > 0 ? rate : null;
        final ad = double.tryParse(cfg['org.reimb_allowance_day'] ?? '') ?? 0;
        _allowDefault = cfg['org.reimb_allowance_print'] == 'false' || ad < 0 ? 0 : ad;
        _paMode = paMode;
        _roles = {for (final u in r[6] as List) '${u['id']}': '${u['role'] ?? ''}'};
        _loading = false;
        _missing = false;
      });
      ref.invalidate(reimbTodoCountProvider);
      if (!_openedLink && widget.openId != null) {
        _openedLink = true;
        final c = _claims.where((x) => x['id'] == widget.openId).firstOrNull;
        if (c != null) {
          setState(() => _tab = 'all');
          _open(c);
        }
      }
    } catch (_) {
      if (mounted) setState(() { _loading = false; _missing = true; });
    }
  }

  static int _dayCount(List<Map<String, dynamic>> ls) => ls.map((l) => '${l['day']}').toSet().length;

  // ── figures ───────────────────────────────────────────────────────────────
  /// Lines of [c] already paid on ANOTHER claim.
  /// The approved / paid claim (other than [c]) that already covers [tripId].
  Map<String, dynamic>? _coveredBy(Map c, String? tripId) {
    final p = _paidTrips[tripId];
    if (p != null && p['claim_id'] != c['id']) {
      return _claims.where((x) => x['id'] == p['claim_id']).firstOrNull ?? {'id': p['claim_id'], 'status': 'paid', 'paid_on': p['paid_on']};
    }
    for (final o in _claims) {
      if (o['id'] == c['id'] || (o['status'] != 'approved' && o['status'] != 'paid')) continue;
      if ((_lines[o['id']] ?? const []).any((l) => l['trip_id'] == tripId)) return o;
    }
    return null;
  }

  /// Lines of [c] already approved or paid on ANOTHER claim (left out of its amount).
  List<Map<String, dynamic>> _paidElsewhere(Map c) => (_lines[c['id']] ?? const [])
      .where((l) => _coveredBy(c, l['trip_id'] as String?) != null)
      .toList();

  double _unpaidKm(Map c) {
    if (c['unpaid_km'] != null && c['status'] != 'pending') return (c['unpaid_km'] as num).toDouble();
    final pe = {for (final l in _paidElsewhere(c)) l['trip_id']};
    return (_lines[c['id']] ?? const [])
        .where((l) => !pe.contains(l['trip_id']))
        .fold<double>(0, (s, l) => s + ((l['km'] as num?) ?? 0).toDouble());
  }

  /// The day's allowance on [c] (approver's figure, else the default), or
  /// null when that day is already approved on another claim.
  double? _dayAllowance(Map c, String day) {
    final ls = (_lines[c['id']] ?? const <Map<String, dynamic>>[]).where((l) => '${l['day']}'.startsWith(day)).toList();
    if (ls.isEmpty || ls.every((l) => _coveredBy(c, l['trip_id'] as String?) != null)) return null;
    final adj = [
      for (final l in ls)
        if ((_adj[c['id']]?['${l['trip_id']}']?['allowance']) != null)
          ((_adj[c['id']]!['${l['trip_id']}']!['allowance']) as num).toDouble(),
    ];
    return adj.isEmpty ? _allowDefault : adj.reduce((a, b) => a > b ? a : b);
  }

  /// Allowance of the whole claim (days not approved elsewhere).
  double _allowance(Map c) {
    final days = {for (final l in _lines[c['id']] ?? const <Map<String, dynamic>>[]) '${l['day']}'.substring(0, 10)};
    return days.fold<double>(0, (s, d) => s + (_dayAllowance(c, d) ?? 0));
  }

  /// Worked out: distance × rate + allowance (null when neither is set).
  num? _workedOut(Map c) {
    final allow = _allowance(c);
    if (_rate == null && allow <= 0) return null;
    return (_unpaidKm(c) * (_rate ?? 0)).round() + allow.round();
  }

  num? _amount(Map c) {
    if (c['status'] == 'paid') return c['paid_amount'] as num?;
    if (c['status'] != 'pending' && c['amount'] != null) return c['amount'] as num;
    return _workedOut(c);
  }

  String _dates(Map c) {
    final a = DateTime.tryParse('${c['date_from'] ?? ''}');
    final b = DateTime.tryParse('${c['date_to'] ?? ''}');
    if (a == null) return '—';
    if (b == null || a == b) return DateFormat('d MMM yyyy').format(a);
    if (a.year == b.year && a.month == b.month) return '${a.day} – ${DateFormat('d MMM yyyy').format(b)}';
    return '${DateFormat('d MMM').format(a)} – ${DateFormat('d MMM yyyy').format(b)}';
  }

  String _role(Map c) => switch (_roles[c['claimant_id']]) {
        'driver' => 'Driver',
        'salesperson' => 'Salesperson',
        final r? when r.isNotEmpty => r[0].toUpperCase() + r.substring(1),
        _ => '',
      };

  /// A pending claim whose every day is already approved on another claim — the pill says "Nothing to claim".
  bool _nothingToClaim(Map c) => c['status'] == 'pending' && _paidElsewhere(c).isNotEmpty && _unpaidKm(c) <= 0.0001;

  List<Map<String, dynamic>> get _shown {
    final l = claimsShown(claims: _claims, tab: _tab, query: _q, onlyCombined: _onlyCombined);
    return _showNothing ? l : l.where((c) => !_nothingToClaim(c)).toList();
  }

  /// Shares an approved claim: a message with its details and the public check link, on WhatsApp, or just
  /// the link copied.
  Future<void> _share(Map<String, dynamic> c, ClaimShare how) async {
    final link = _verifyUrl(c);
    if (link == null) {
      _snack('This claim has no link yet. Open it once and try again.');
      return;
    }
    if (how == ClaimShare.copyLink) {
      await Clipboard.setData(ClipboardData(text: link));
      _snack('Link copied');
      return;
    }
    final amt = _amount(c);
    final rateUsed = c['rate'] ?? _rate;
    final text = reimbShareText(
      claimant: '${c['claimant_name'] ?? ''}',
      docLabel: c['doc_type'] == 'combined_summary' ? 'Combined Trip Summary' : 'Trip Summary',
      dates: _dates(c),
      km: _km(c['km'] as num?),
      amount: amt == null ? '' : _rs(amt),
      rateNote: rateUsed == null ? null : '@ Rs ${NumberFormat('#,##0.##').format(rateUsed)}/km',
      link: link,
    );
    final ok = await launchUrl(whatsAppShareUri(text), mode: LaunchMode.externalApplication);
    if (!ok) _snack('Could not open WhatsApp. The link is copied instead.');
    if (!ok) await Clipboard.setData(ClipboardData(text: link));
  }

